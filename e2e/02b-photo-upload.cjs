const { chromium, launchOptions } = require('./lib.cjs');
const { execSync } = require('child_process');
const sql = (q) => execSync(`psql -tA postgresql://postgres:postgres@127.0.0.1:54322/postgres -c "${q}"`).toString().trim();
(async () => {
  const browser = await chromium.launch(launchOptions);
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('http://localhost:8081', { timeout: 120000 });
  await page.getByText("I'm looking for work").click({ timeout: 120000 });
  await page.getByText('Demo worker').click();
  await page.getByRole('tab', { name: /Profile/ }).click();
  await page.locator('input[value="Sam Taylor"]').waitFor({ timeout: 15000 });
  const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.getByRole('button', { name: /Choose photo/ }).click()]);
  await chooser.setFiles(__dirname + '/fixtures/photo.jpg');
  await page.waitForTimeout(1500);
  await page.getByRole('button', { name: /Save changes/ }).click();
  await page.getByText('Profile saved').waitFor({ timeout: 15000 });
  const path = sql(`select photo_path from worker_profiles where user_id='11111111-1111-1111-1111-111111111111'`);
  const objs = sql(`select count(*) from storage.objects where bucket_id='avatars' and name like '11111111-1111-1111-1111-111111111111/%'`);
  console.log('photo_path:', path, 'objects:', objs);
  await page.reload();
  await page.locator('input[value="Sam Taylor"]').waitFor({ timeout: 30000 });
  await page.waitForTimeout(2000);
  const img = await page.evaluate(() => [...document.querySelectorAll('img')].map(i => i.src).filter(s => s.includes('avatars')));
  console.log('signed img loaded:', img.length > 0 ? img[0].slice(0, 90) + '…' : 'none');
  await page.screenshot({ path: __dirname + '/m2-8-photo.png' });
  console.log('errors:', errors.length ? errors : 'none');
  await browser.close();
})().catch(e => { console.error('FAIL', e.message.split('\n')[0]); process.exit(1); });
