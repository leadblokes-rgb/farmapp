// Copies docs/legal/*.md into the app as strings (Metro can't import Markdown).
// Run `npm run build:legal` after editing the documents; a unit test checks they're in sync.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, 'docs/legal', f), 'utf8');
const out = `// Generated by scripts/build-legal.mjs from docs/legal/*.md. Do not edit by hand.
export const legalDocuments = ${JSON.stringify({ terms: read('terms.md'), privacy: read('privacy-policy.md') }, null, 2)} as const;
`;
writeFileSync(join(root, 'apps/mobile/src/features/legal/documents.generated.ts'), out);
console.log('Wrote apps/mobile/src/features/legal/documents.generated.ts');
