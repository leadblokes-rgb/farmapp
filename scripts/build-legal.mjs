// Copies docs/legal/*.md into the app as strings (Metro can't import Markdown), and builds the
// matching public web pages in website/ (privacy.html, terms.html, support.html), which the app
// stores link to as the privacy policy and support URLs.
// Run `npm run build:legal` after editing the documents; a unit test checks everything is in sync.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, 'docs/legal', f), 'utf8');
const docs = { terms: read('terms.md'), privacy: read('privacy-policy.md') };

// ---- App copy ----
const out = `// Generated by scripts/build-legal.mjs from docs/legal/*.md. Do not edit by hand.
export const legalDocuments = ${JSON.stringify(docs, null, 2)} as const;
`;
writeFileSync(join(root, 'apps/mobile/src/features/legal/documents.generated.ts'), out);
console.log('Wrote apps/mobile/src/features/legal/documents.generated.ts');

// ---- Website ----
const legalConfig = readFileSync(join(root, 'packages/shared/src/config/legal.ts'), 'utf8');
const supportEmail = /supportEmail:\s*'([^']+)'/.exec(legalConfig)[1];

const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const inline = (s) =>
  escape(s)
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');

/** The small subset of Markdown the legal documents use: headings, paragraphs, lists, bold, links. */
function markdownToHtml(md) {
  const html = [];
  let list = false;
  let para = [];
  const flush = () => {
    if (para.length) html.push(`<p>${inline(para.join(' '))}</p>`);
    para = [];
  };
  for (const line of md.split('\n')) {
    const heading = /^(#{1,3}) (.*)$/.exec(line);
    const item = /^- (.*)$/.exec(line);
    if (!item && list) {
      html.push('</ul>');
      list = false;
    }
    if (heading) {
      flush();
      html.push(`<h${heading[1].length}>${inline(heading[2])}</h${heading[1].length}>`);
    } else if (item) {
      flush();
      if (!list) html.push('<ul>');
      list = true;
      html.push(`<li>${inline(item[1])}</li>`);
    } else if (line.trim() === '') {
      flush();
    } else {
      para.push(line.trim());
    }
  }
  flush();
  if (list) html.push('</ul>');
  return html.join('\n');
}

