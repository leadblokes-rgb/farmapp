// Bundles workspace packages that Edge Functions use into plain ESM, so Deno runs the exact same
// matching code as the app. Run after changing packages/matching or packages/shared:
//   npm run build:functions
import { build } from 'esbuild';

export const matchingBundleOptions = {
  entryPoints: ['packages/matching/src/index.ts'],
  outfile: 'supabase/functions/_shared/matching.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2022',
  treeShaking: true,
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-functions.mjs from packages/matching. Do not edit.' },
};

if (import.meta.url === `file://${process.argv[1]}`) {
  await build(matchingBundleOptions);
  console.log('Built supabase/functions/_shared/matching.js');
}
